/**
 * GST return module records.
 *
 * Kept in their own namespace, and their own Firestore collections, because
 * returns are a separate concern from billing. Nothing here appears on an
 * invoice screen, and the whole module is hidden from businesses it does not
 * apply to.
 */

import type { CivilDate, MonthPeriod } from '@/lib/dates';

export type Iso8601 = string;

/** Which official form a period's work belongs to. */
export type ReturnForm = 'GSTR-1' | 'GSTR-3B' | 'GSTR-1A' | 'IFF';

/**
 * The lifecycle of a period, mapped to what is actually TRUE at each point.
 *
 * The distinction that matters most: `uploaded` and `filed` are different
 * states, and only an authoritative acknowledgement moves a period to `filed`.
 * A generated JSON, an upload receipt, a challan or a payment confirmation is
 * never, on its own, proof that a return was filed.
 */
export type ReturnStatus =
  | 'draft'
  | 'needs-review'
  | 'ready'
  | 'uploaded'
  | 'filed'
  | 'reported-filed-unverified'
  | 'failed'
  | 'status-unknown';

export const RETURN_STATUS_LABELS: Record<ReturnStatus, string> = {
  draft: 'Being prepared',
  'needs-review': 'Needs checking',
  ready: 'Ready',
  uploaded: 'Uploaded — being processed',
  filed: 'Filed',
  'reported-filed-unverified': 'Reported filed — verification pending',
  failed: 'Failed',
  'status-unknown': 'Status unknown',
};

