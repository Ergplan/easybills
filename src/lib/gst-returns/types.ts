/** Whether input tax credit on a purchase may actually be taken. */
export type ItcEligibility = 'not-reviewed' | 'eligible' | 'ineligible' | 'blocked' | 'partial' | 'deferred';

export interface SupplierBillRecord {
  id: string;
  /** The supplier's GSTIN, where the purchase is from a registered supplier. */
  supplierGstin: string | null;
  supplierName: string;
  /** The supplier's OWN document number, preserved exactly as printed. */
  documentNumber: string;
  /** A normalised form used only for matching. Never shown as the document number. */
  matchKey: string;
  documentDate: CivilDate;
  documentType: 'invoice' | 'debit-note' | 'credit-note';
  /** The period this purchase is being accounted in. */
  period: MonthPeriod;

  taxableValuePaise: number;
  cgstPaise: number;
  sgstPaise: number;
  igstPaise: number;
  cessPaise: number;

  /**
   * Reviewed eligibility. Defaults to `not-reviewed`: appearing in GSTR-2B does
   * NOT by itself make credit claimable, so nothing is claimed automatically.
   */
  itcEligibility: ItcEligibility;
  /** The portion the owner confirmed as claimable, when partial. */
  eligibleCgstPaise: number;
  eligibleSgstPaise: number;
  eligibleIgstPaise: number;
  eligibleCessPaise: number;
  eligibilityNote: string | null;
  eligibilityReviewedByUid: string | null;
  eligibilityReviewedAt: Iso8601 | null;

  /** Reverse charge purchases carry their own liability. */
  reverseCharge: boolean;

  /** Where this record came from. */
  source: 'manual' | 'csv-import' | 'portal-import';
  importBatchId: string | null;
  createdAt: Iso8601;
  updatedAt: Iso8601;
}

/** A sale raised outside this app that still belongs in the return. */
export interface ExternalSaleRecord {
  id: string;
  /** The original document number. NEVER regenerated by this app. */
  documentNumber: string;
  matchKey: string;
  documentDate: CivilDate;
  period: MonthPeriod;
  customerGstin: string | null;
  customerName: string;
  placeOfSupplyStateCode: string | null;
  documentType: 'invoice' | 'credit-note' | 'debit-note';
  taxableValuePaise: number;
  cgstPaise: number;
  sgstPaise: number;
  igstPaise: number;
  cessPaise: number;
  taxRateBp: number;
  source: 'csv-import' | 'portal-import';
  importBatchId: string;
  createdAt: Iso8601;
}

export interface ImportBatchRecord {
  id: string;
  kind: 'supplier-bills' | 'external-sales' | 'gstr-2b';
  filename: string;
  /** SHA-256 of the uploaded bytes, so re-importing the same file is detectable. */
  fileHash: string;
  sizeBytes: number;
  period: MonthPeriod | null;
  rowsSeen: number;
  rowsImported: number;
  rowsSkippedDuplicate: number;
  rowsRejected: number;
  errors: Array<{ row: number; message: string }>;
  importedByUid: string;
  importedAt: Iso8601;
}

/**
 * An imported portal statement (GSTR-2B and friends).
 *
 * Provenance is the point: the period it covers, when the PORTAL generated it,
 * when we imported it, and the hash of what we imported. Stale statements are
 * detectable and block readiness instead of silently underpinning a return.
 */
export interface GstStatementSnapshotRecord {
  id: string;
  gstin: string;
  statementType: 'GSTR-2B' | 'GSTR-1-summary' | 'GSTR-3B-summary' | 'ledger-summary';
  period: MonthPeriod;
  /** When the portal says it generated or recomputed this statement. */
  generatedAt: Iso8601 | null;
  importedAt: Iso8601;
  importedByUid: string;
  fileHash: string;
  importVersion: number;
  /** Parsed rows, normalised. */
  rows: Array<{
    supplierGstin: string | null;
    supplierName: string;
    documentNumber: string;
    matchKey: string;
    documentDate: CivilDate;
    documentType: 'invoice' | 'debit-note' | 'credit-note';
    taxableValuePaise: number;
    cgstPaise: number;
    sgstPaise: number;
    igstPaise: number;
    cessPaise: number;
    /** What the statement itself says about availability. Not our judgement. */
    statementItcAvailable: boolean | null;
  }>;
  /** Marked stale when source data changed after this snapshot was taken. */
  supersededBySnapshotId: string | null;
}

