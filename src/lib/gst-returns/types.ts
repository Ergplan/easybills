export interface CompletenessDeclaration {
  allSalesIncluded: boolean;
  allPurchasesIncluded: boolean;
  otherLiabilitiesConsidered: boolean;
  /** Explicitly asked, because "no bills" does not mean "nil return". */
  confirmedNilIfEmpty: boolean;
  declaredByUid: string;
  declaredAt: Iso8601;
}

export interface ReturnPeriodRecord {
  /** `${gstin}__${form}__${period}` */
  id: string;
  gstin: string;
  form: ReturnForm;
  period: MonthPeriod;
  /** For QRMP, the quarter a monthly period rolls into. */
  quarterPeriod: MonthPeriod | null;
  status: ReturnStatus;
  /** Verified statutory due date, or null when we do not have a verified rule. */
  dueDate: CivilDate | null;
  dueDateSource: string | null;
  completeness: CompletenessDeclaration | null;
  /** The version the owner approved, if any. */
  approvedVersionId: string | null;
  currentVersionId: string | null;
  blockingReasons: string[];
  lastPreparedAt: Iso8601 | null;
  updatedAt: Iso8601;
}

/**
 * An immutable snapshot of a prepared return.
 *
 * Reopening any source data after review invalidates the approval: the
 * `sourceFingerprint` is recomputed and compared, so an approval can never be
 * carried over onto a payload the owner did not see.
 */
export interface ReturnVersionRecord {
  id: string;
  returnPeriodId: string;
  gstin: string;
  form: ReturnForm;
  period: MonthPeriod;
  versionNumber: number;
  createdAt: Iso8601;
  createdByUid: string;

  /** Hash over every source record that fed this version. */
  sourceFingerprint: string;
  /** Hash of the approved payload, bound to an approval. */
  payloadHash: string;
  rulePackVersion: string;
  schemaVersion: string | null;

  /** The computed tables. Shape depends on the form. */
  workings: Record<string, unknown>;

  approvedByUid: string | null;
  approvedAt: Iso8601 | null;
  /** Set when a later change made this approval invalid. */
  invalidatedAt: Iso8601 | null;
  invalidationReason: string | null;
}

