#!/usr/bin/env python3
"""Regenerate themes.css and tokens.ts from tokens.json.

Usage:  python3 design/tokens/build.py
Both outputs are generated files. Edit tokens.json, never the outputs.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
T = json.loads((HERE / "tokens.json").read_text())


def flat(prefix, obj, out):
    for k, v in obj.items():
        name = f"{prefix}-{k}"
        if isinstance(v, dict):
            flat(name, v, out)
        else:
            out[name] = v
    return out


def theme_vars(theme):
    t = T["themes"][theme]
    v = {}
    flat("--eb", t["color"], v)
    flat("--eb-g", t["gradient"], v)
    flat("--eb-shadow", t["shadow"], v)
    for i, a in enumerate(t["avatar"]):
        v[f"--eb-avatar-{i}"] = a
    v["--eb-hero-style"] = f'"{t["hero-style"]}"'
    return v


def block(selector, vars_, scheme, indent="  "):
    lines = [f"{selector} {{", f"{indent}color-scheme: {scheme};"]
    lines += [f"{indent}{k}: {val};" for k, val in vars_.items()]
    lines.append("}")
    return "\n".join(lines)


shared = {}
flat("--eb-radius", T["shared"]["radius"], shared)
flat("--eb-space", T["shared"]["space"], shared)
flat("--eb-size", T["shared"]["size"], shared)
flat("--eb", T["shared"]["semantic-fixed"], shared)
shared["--eb-font"] = T["meta"]["fontFamily"]
for k, spec in T["shared"]["type"].items():
    for p, val in spec.items():
        shared[f"--eb-type-{k}-{p}"] = val

n, h = theme_vars("narangi"), theme_vars("harmony")

css = [
    "/* GENERATED by design/tokens/build.py from tokens.json. Do not edit by hand. */",
    "/* Usage: <html data-theme=\"narangi\"> or <html data-theme=\"harmony\">.",
    "   With no data-theme, the OS setting decides: light = narangi, dark = harmony. */",
    "",
    ":root {",
    *[f"  {k}: {v};" for k, v in shared.items()],
    "}",
    "",
    block(':root, :root[data-theme="narangi"]', n, "light"),
    "",
    block(':root[data-theme="harmony"]', h, "dark"),
    "",
    "@media (prefers-color-scheme: dark) {",
    block('  :root:not([data-theme])', h, "dark", indent="    "),
    "}",
    "",
    "/* Base layer every screen sits on */",
    "html, body {",
    "  background-color: var(--eb-bg);",
    "  background-image: var(--eb-g-screen-glow), radial-gradient(var(--eb-bg-dots) 1px, transparent 1.2px);",
    "  background-size: 100% 100%, var(--eb-bg-dots-size) var(--eb-bg-dots-size);",
    "  color: var(--eb-text);",
    "  font-family: var(--eb-font);",
    "  -webkit-font-smoothing: antialiased;",
    "}",
    ".eb-num { font-variant-numeric: tabular-nums; }",
    ":focus-visible { outline: 2px solid var(--eb-focus); outline-offset: 2px; }",
    "",
]
(HERE / "themes.css").write_text("\n".join(css))


def js_obj(d, ind=2):
    pad = " " * ind
    parts = []
    for k, v in d.items():
        key = json.dumps(k)
        if isinstance(v, dict):
            parts.append(f"{pad}{key}: {js_obj(v, ind + 2)}")
        else:
            parts.append(f"{pad}{key}: {json.dumps(v)}")
    return "{\n" + ",\n".join(parts) + "\n" + " " * (ind - 2) + "}"


ts = f"""// GENERATED by design/tokens/build.py from tokens.json. Do not edit by hand.
export type ThemeName = "narangi" | "harmony";
export const THEMES: ThemeName[] = ["narangi", "harmony"];
export const DEFAULT_THEME: ThemeName = "narangi";
export const SYSTEM_DARK_THEME: ThemeName = "harmony";

export const shared = {js_obj(T["shared"])} as const;

export const themes = {js_obj(T["themes"])} as const;

/** CSS variable reference, e.g. v("accent") -> "var(--eb-accent)" */
export const v = (name: string) => `var(--eb-${{name}})`;

/** Apply a theme at runtime. Persist the choice on the user profile (profile.theme). */
export function applyTheme(theme: ThemeName | "system") {{
  const root = document.documentElement;
  if (theme === "system") root.removeAttribute("data-theme");
  else root.setAttribute("data-theme", theme);
}}
"""
(HERE / "tokens.ts").write_text(ts)
print("wrote themes.css and tokens.ts")
